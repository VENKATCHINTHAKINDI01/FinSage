"""
Data Validation Module
======================

Central validation framework for all data fetched from the internet,
generated by LLMs, or computed by financial tools.

Ensures reliability by:
- Validating web search results (URL, freshness, credibility)
- Validating LLM JSON responses (schema, ranges, hallucination detection)
- Validating financial calculations (limits, brackets, sanity checks)
- Generating structured validation reports with confidence scores
"""

import json
import logging
import re
from dataclasses import dataclass, field
from datetime import datetime, timezone
from typing import Any
from urllib.parse import urlparse

logger = logging.getLogger(__name__)


# ============================================================================
# VALIDATION REPORT
# ============================================================================

@dataclass
class ValidationReport:
    """Structured validation output attached to every agent/tool result."""
    is_valid: bool = True
    confidence_score: float = 1.0
    warnings: list[str] = field(default_factory=list)
    corrections_applied: list[str] = field(default_factory=list)
    sources_verified: list[dict[str, Any]] = field(default_factory=list)
    validation_timestamp: str = field(default_factory=lambda: datetime.now(timezone.utc).isoformat())

    def add_warning(self, warning: str):
        self.warnings.append(warning)
        # Degrade confidence for each warning
        self.confidence_score = max(0.0, self.confidence_score - 0.1)

    def add_correction(self, correction: str):
        self.corrections_applied.append(correction)

    def add_source(self, url: str, credibility: float, domain: str):
        self.sources_verified.append({
            "url": url,
            "credibility_score": credibility,
            "domain": domain,
            "verified_at": datetime.now(timezone.utc).isoformat()
        })

    def to_dict(self) -> dict[str, Any]:
        return {
            "is_valid": self.is_valid,
            "confidence_score": round(self.confidence_score, 2),
            "warnings": self.warnings,
            "corrections_applied": self.corrections_applied,
            "sources_verified": self.sources_verified,
            "validation_timestamp": self.validation_timestamp
        }

    @property
    def status_badge(self) -> str:
        """Return a status badge string for display."""
        if self.confidence_score >= 0.8:
            return "🟢 Verified"
        elif self.confidence_score >= 0.5:
            return "🟡 Partially Verified"
        else:
            return "🔴 Unverified"


