class FinancialDataValidator:
    """Validates financial calculations and data consistency."""

    def __init__(self):
        self.logger = logging.getLogger("validator.financial")

    def validate_tax_calculation(
        self,
        calculation: dict[str, Any]
    ) -> tuple[dict[str, Any], ValidationReport]:
        """Validate tax calculation results."""
        report = ValidationReport()

        total_income = calculation.get("total_income", 0)
        deductions = calculation.get("deductions", 0)
        taxable_income = calculation.get("taxable_income", 0)
        total_tax = calculation.get("total_tax_liability", 0)

        # Sanity: taxable income can't exceed total income
        if taxable_income > total_income:
            report.add_warning("Taxable income exceeds total income")
            report.add_correction(f"Capped taxable income from ₹{taxable_income:,.0f} to ₹{total_income:,.0f}")
            calculation["taxable_income"] = total_income

        # Sanity: tax can't exceed taxable income
        if total_tax > taxable_income and taxable_income > 0:
            report.add_warning(f"Tax (₹{total_tax:,.0f}) exceeds taxable income (₹{taxable_income:,.0f})")
            report.confidence_score = max(0.3, report.confidence_score - 0.3)

        # Sanity: deductions can't exceed total income
        if deductions > total_income and total_income > 0:
            report.add_warning("Total deductions exceed total income")
            report.confidence_score = max(0.4, report.confidence_score - 0.2)

        # Effective tax rate can't exceed max rate + cess
        if total_income > 0:
            effective_rate = total_tax / total_income
            max_effective = INDIA_TAX_GROUND_TRUTH["max_tax_rate"] * (1 + INDIA_TAX_GROUND_TRUTH["cess_rate"])
            if effective_rate > max_effective + 0.05:  # 5% buffer for surcharge
                report.add_warning(
                    f"Effective tax rate ({effective_rate:.1%}) seems too high — max possible ~{max_effective:.1%}"
                )

        # Negative values check
        for field_name in ["total_income", "taxable_income", "total_tax_liability"]:
            val = calculation.get(field_name, 0)
            if isinstance(val, (int, float)) and val < 0:
                report.add_warning(f"Negative value for {field_name}: {val}")

        return calculation, report

    def validate_savings_estimate(
        self,
        savings: float,
        total_income: float,
        total_deductions: float
    ) -> tuple[float, ValidationReport]:
        """Validate that estimated savings are realistic."""
        report = ValidationReport()

        if total_income <= 0:
            return savings, report

        # Savings can't exceed total income
        if savings > total_income:
            report.add_warning(f"Estimated savings (₹{savings:,.0f}) exceed total income (₹{total_income:,.0f})")
            savings = min(savings, total_income * 0.30)  # Cap at 30% of income
            report.add_correction(f"Capped savings estimate to ₹{savings:,.0f}")

        # Savings from deductions can't exceed the max marginal rate * deductions
        max_savings = total_deductions * (INDIA_TAX_GROUND_TRUTH["max_tax_rate"] + INDIA_TAX_GROUND_TRUTH["cess_rate"])
        if savings > max_savings * 1.2:  # 20% buffer
            report.add_warning(
                f"Savings seem inflated: ₹{savings:,.0f} vs max possible ₹{max_savings:,.0f}"
            )

        return savings, report


