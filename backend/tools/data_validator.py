class DataValidator:
    """Unified validator that combines all validation modules."""

    def __init__(self):
        self.web = WebDataValidator()
        self.llm = LLMResponseValidator()
        self.financial = FinancialDataValidator()
        self.logger = logging.getLogger("validator")
        self.logger.info("DataValidator initialized with web, LLM, and financial validators")

    def validate_tool_result(
        self,
        tool_name: str,
        result: dict[str, Any]
    ) -> tuple[dict[str, Any], ValidationReport]:
        """
        Validate a tool's result based on its category.

        Args:
            tool_name: Name of the tool that produced the result
            result: Raw tool result

        Returns:
            (validated_result, validation_report)
        """
        report = ValidationReport()

        if not result.get("success", False):
            report.add_warning(f"Tool '{tool_name}' returned failure")
            report.confidence_score = 0.2
            result["validation"] = report.to_dict()
            return result, report

        # Route to appropriate validator based on tool name
        if tool_name in ("web_search_tavily", "search_latest_tax_rules", "search_government_schemes"):
            result, report = self.web.validate_search_results(result, tool_name)

        elif tool_name in ("calculate_tax_liability",):
            calc_data = result.get("result", {})
            if isinstance(calc_data, dict):
                validated_calc, report = self.financial.validate_tax_calculation(calc_data)
                result["result"] = validated_calc

        elif tool_name in ("calculate_deduction_impact", "estimate_tax_refund"):
            # Basic numeric validation
            calc_data = result.get("result", {})
            if isinstance(calc_data, dict):
                for key, val in calc_data.items():
                    if isinstance(val, (int, float)) and val < 0 and key != "refund":
                        report.add_warning(f"Negative value in {tool_name}: {key}={val}")

        # Attach validation metadata
        result["validated"] = report.is_valid
        result["validation_warnings"] = report.warnings
        result["validation"] = report.to_dict()

        return result, report
