class WebDataValidator:
    """Validates data fetched from web search APIs (Tavily, etc.)."""

    def __init__(self):
        self.logger = logging.getLogger("validator.web")

    def validate_search_results(
        self,
        results: dict[str, Any],
        query: str
    ) -> tuple[dict[str, Any], ValidationReport]:
        """
        Validate web search results and add credibility metadata.

        Args:
            results: Raw search results from Tavily/fallback
            query: Original search query

        Returns:
            (validated_results, validation_report)
        """
        report = ValidationReport()

        if not results.get("success"):
            report.is_valid = False
            report.confidence_score = 0.0
            report.add_warning("Search request failed")
            return results, report

        search_results = results.get("result", {}).get("results", [])

        if not search_results:
            report.add_warning("No search results returned")
            report.confidence_score = 0.3
            return results, report

        validated_results = []
        for item in search_results:
            validated_item = self._validate_single_result(item, report)
            if validated_item:
                validated_results.append(validated_item)

        # Update results with validated items
        results["result"]["results"] = validated_results
        results["validation"] = report.to_dict()

        # Overall confidence based on source quality
        if validated_results:
            avg_credibility = sum(
                r.get("credibility_score", 0.5) for r in validated_results
            ) / len(validated_results)
            report.confidence_score = min(report.confidence_score, avg_credibility)

        return results, report

    def _validate_single_result(
        self,
        item: dict[str, Any],
        report: ValidationReport
    ) -> dict[str, Any] | None:
        """Validate a single search result item."""
        url = item.get("url", "")
        title = item.get("title", "")
        content = item.get("content", "")

        # URL format validation
        if url:
            try:
                parsed = urlparse(url)
                if not parsed.scheme or not parsed.netloc:
                    report.add_warning(f"Malformed URL skipped: {url[:50]}")
                    return None
                domain = parsed.netloc.lower().replace("www.", "")
            except Exception:
                domain = "unknown"
        else:
            domain = "unknown"

        # Content sanitization — strip dangerous patterns
        if content:
            content = self._sanitize_content(content)

        # Source credibility scoring
        credibility = self._score_credibility(domain)
        report.add_source(url, credibility, domain)

        # Freshness check (if date metadata available)
        date_str = item.get("date", item.get("published_date"))
        freshness_warning = self._check_freshness(date_str)
        if freshness_warning:
            report.add_warning(freshness_warning)

        # Return validated item with metadata
        return {
            **item,
            "content": content,
            "credibility_score": credibility,
            "domain": domain,
            "is_trusted_source": credibility >= 0.8,
            "validated": True
        }

    def _score_credibility(self, domain: str) -> float:
        """Score source credibility based on domain."""
        # Check exact match first
        if domain in TRUSTED_DOMAINS:
            return TRUSTED_DOMAINS[domain]

        # Check subdomain match
        for trusted, score in TRUSTED_DOMAINS.items():
            if domain.endswith(f".{trusted}") or trusted.endswith(f".{domain}"):
                return score * 0.9

        # Government domains get high base credibility
        if domain.endswith(".gov.in") or domain.endswith(".nic.in"):
            return 0.85

        # Default credibility for unknown sources
        return 0.4

    def _sanitize_content(self, content: str) -> str:
        """Sanitize content by removing potentially harmful patterns."""
        # Remove HTML tags
        content = re.sub(r'<[^>]+>', '', content)
        # Remove script injections
        content = re.sub(r'(?i)<script.*?</script>', '', content)
        content = re.sub(r'(?i)javascript:', '', content)
        # Remove excessive whitespace
        content = re.sub(r'\s+', ' ', content).strip()
        # Truncate extremely long content
        if len(content) > 5000:
            content = content[:5000] + "..."
        return content

    def _check_freshness(self, date_str: str | None) -> str | None:
        """Check if the data is fresh enough."""
        if not date_str:
            return None

        try:
            # Try common date formats
            for fmt in ["%Y-%m-%d", "%Y-%m-%dT%H:%M:%S", "%d-%m-%Y", "%Y/%m/%d"]:
                try:
                    date = datetime.strptime(date_str.split("T")[0] if "T" in date_str else date_str, fmt)
                    age_days = (datetime.now(timezone.utc) - date).days
                    if age_days > 365:
                        return f"Source data is {age_days} days old — may be outdated"
                    elif age_days > 180:
                        return f"Source data is {age_days} days old — verify for current FY"
                    return None
                except ValueError:
                    continue
        except Exception:
            pass

        return None


