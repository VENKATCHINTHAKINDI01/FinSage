class LLMResponseValidator:
    """Validates LLM (Groq) responses — JSON parsing, schema, hallucination checks."""

    def __init__(self):
        self.logger = logging.getLogger("validator.llm")

    def parse_json_response(self, raw_response: str) -> tuple[dict | None, ValidationReport]:
        """
        Robustly parse JSON from LLM response with multiple fallback strategies.

        Args:
            raw_response: Raw text from LLM

        Returns:
            (parsed_dict_or_None, validation_report)
        """
        report = ValidationReport()

        if not raw_response or not raw_response.strip():
            report.is_valid = False
            report.confidence_score = 0.0
            report.add_warning("Empty LLM response")
            return None, report

        text = raw_response.strip()

        # Strategy 1: Direct JSON parse
        try:
            parsed = json.loads(text)
            self.logger.debug("JSON parsed directly")
            return parsed, report
        except json.JSONDecodeError:
            pass

        # Strategy 2: Extract from markdown code blocks
        code_block_patterns = [
            r'```json\s*\n?(.*?)\n?\s*```',
            r'```\s*\n?(.*?)\n?\s*```',
        ]
        for pattern in code_block_patterns:
            match = re.search(pattern, text, re.DOTALL)
            if match:
                try:
                    parsed = json.loads(match.group(1).strip())
                    report.add_correction("Extracted JSON from markdown code block")
                    return parsed, report
                except json.JSONDecodeError:
                    continue

        # Strategy 3: Find JSON object boundaries
        try:
            # Find first { and last }
            start = text.index('{')
            end = text.rindex('}') + 1
            candidate = text[start:end]
            parsed = json.loads(candidate)
            report.add_correction("Extracted JSON by finding object boundaries")
            return parsed, report
        except (ValueError, json.JSONDecodeError):
            pass

        # Strategy 4: Find JSON array boundaries
        try:
            start = text.index('[')
            end = text.rindex(']') + 1
            candidate = text[start:end]
            parsed = json.loads(candidate)
            report.add_correction("Extracted JSON array by finding boundaries")
            return {"data": parsed}, report
        except (ValueError, json.JSONDecodeError):
            pass

        # Strategy 5: Fix common JSON issues and retry
        try:
            fixed = text
            # Remove trailing commas before } or ]
            fixed = re.sub(r',\s*([}\]])', r'\1', fixed)
            # Replace single quotes with double quotes
            fixed = re.sub(r"(?<![\\])'", '"', fixed)
            # Try to find JSON within
            start = fixed.index('{')
            end = fixed.rindex('}') + 1
            parsed = json.loads(fixed[start:end])
            report.add_correction("Fixed common JSON formatting issues")
            report.add_warning("LLM response required JSON repair")
            return parsed, report
        except (ValueError, json.JSONDecodeError):
            pass

        # All strategies failed
        report.is_valid = False
        report.confidence_score = 0.0
        report.add_warning("Failed to parse JSON from LLM response after all strategies")
        self.logger.error(f"JSON parse failed. Raw response (first 500 chars): {text[:500]}")
        return None, report

    def validate_income_sources(
        self,
        sources: list[dict[str, Any]]
    ) -> tuple[list[dict[str, Any]], ValidationReport]:
        """Validate extracted income sources."""
        report = ValidationReport()
        validated = []

        for source in sources:
            # Required fields check
            if not source.get("type"):
                report.add_warning("Income source missing 'type' field")
                source["type"] = "Other"
                report.add_correction("Defaulted missing income type to 'Other'")

            # Amount validation
            amount = source.get("amount", 0)
            try:
                amount = float(amount)
            except (TypeError, ValueError):
                report.add_warning(f"Invalid amount '{amount}' for {source.get('type')}")
                amount = 0
                report.add_correction(f"Set invalid amount to 0 for {source.get('type')}")

            if amount < 0:
                report.add_warning(f"Negative income amount: {amount}")
                amount = abs(amount)
                report.add_correction(f"Converted negative amount to positive: {amount}")

            if amount > 1_000_000_000:  # > 100 crore — likely hallucination
                report.add_warning(f"Suspiciously large income: ₹{amount:,.0f} — possible hallucination")
                report.confidence_score = max(0.2, report.confidence_score - 0.3)

            source["amount"] = amount
            validated.append(source)

        return validated, report

    def validate_deductions(
        self,
        deductions: list[dict[str, Any]]
    ) -> tuple[list[dict[str, Any]], ValidationReport]:
        """Validate and enforce deduction limits against ground truth."""
        report = ValidationReport()
        validated = []

        for deduction in deductions:
            # Required fields
            if not deduction.get("category"):
                report.add_warning("Deduction missing 'category' field")
                deduction["category"] = "Uncategorized"

            # AGT-001: amount_known=false is a deliberate "the model was not
            # given a real figure to work from" signal (see the prompt in
            # deduction_hunter.py), not malformed data — leave it as-is
            # rather than logging it alongside genuinely invalid input and
            # coercing it to a misleading 0.
            if deduction.get("amount_known") is False:
                deduction["amount"] = None
                validated.append(deduction)
                continue

            # Amount validation
            amount = deduction.get("amount", 0)
            try:
                amount = float(amount)
            except (TypeError, ValueError):
                report.add_warning(f"Invalid deduction amount for {deduction.get('category')}")
                amount = 0

            if amount < 0:
                amount = abs(amount)
                report.add_correction(f"Converted negative deduction to positive: {amount}")

            # Enforce section limits from ground truth
            scheme_code = deduction.get("scheme_code", "")
            if scheme_code:
                # Normalize scheme code
                code_normalized = scheme_code.upper().replace("SECTION ", "").replace("SEC ", "").strip()
                limit = INDIA_TAX_GROUND_TRUTH["deduction_limits"].get(code_normalized)

                if limit is not None and amount > limit:
                    report.add_warning(
                        f"Section {code_normalized}: ₹{amount:,.0f} exceeds limit of ₹{limit:,.0f}"
                    )
                    report.add_correction(
                        f"Capped Section {code_normalized} deduction from ₹{amount:,.0f} to ₹{limit:,.0f}"
                    )
                    amount = limit

            deduction["amount"] = amount
            validated.append(deduction)

        return validated, report

    def validate_intent_response(
        self,
        response_data: dict[str, Any] | None
    ) -> tuple[dict[str, Any], ValidationReport]:
        """Validate intent detection response from LLM."""
        report = ValidationReport()

        if not response_data:
            report.is_valid = False
            report.confidence_score = 0.0
            report.add_warning("No intent data returned from LLM")
            return {"intent": "GENERAL", "confidence": 0.0, "reasoning": "Parse failure"}, report

        # Validate intent field
        valid_intents = {
            "TAX_DEDUCTION", "TAX_SAVINGS", "INVESTMENT_ADVICE", "PORTFOLIO_ANALYSIS",
            "GOVERNMENT_BENEFITS", "ELIGIBILITY_CHECK", "BUSINESS_EXPENSE",
            "FINANCIAL_PLANNING", "COMPLIANCE_CHECK", "TAX_FILING", "TAX_CALCULATION",
            "CROSS_BORDER_TAX", "PRICE_INTELLIGENCE", "TAX_STRATEGY",
            "WEALTH_PLANNING", "GENERAL"
        }

        intent = response_data.get("intent", "GENERAL").upper()
        if intent not in valid_intents:
            report.add_warning(f"Unknown intent '{intent}' — defaulting to GENERAL")
            report.add_correction(f"Replaced unknown intent '{intent}' with GENERAL")
            response_data["intent"] = "GENERAL"

        # Validate confidence
        confidence = response_data.get("confidence", 0.5)
        try:
            confidence = float(confidence)
            confidence = max(0.0, min(1.0, confidence))
        except (TypeError, ValueError):
            confidence = 0.5
            report.add_correction("Fixed invalid confidence value")
        response_data["confidence"] = confidence

        return response_data, report


